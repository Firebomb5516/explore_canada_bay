/// Localisation for the Explore experience and its JSON-backed content.
///
/// Stable technical values stay in the base JSON. Each record may provide a
/// `translations` object containing locale-specific display fields. Missing
/// translations deliberately fall back to English so lightweight test
/// fixtures and older cached content continue to work.
class ExploreLocalizations {
  const ExploreLocalizations(this.locale);

  final Locale locale;

  static ExploreLocalizations of(BuildContext context) {
    return ExploreLocalizations(Localizations.localeOf(context));
  }

  String get languageCode {
    final code = locale.languageCode.toLowerCase();
    return _values.containsKey(code) ? code : 'en';
  }

  String text(String key, [Map<String, Object> parameters = const {}]) {
    var value = _values[languageCode]?[key] ?? _values['en']?[key] ?? key;
    for (final entry in parameters.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value.toString());
    }
    return value;
  }

  String filterLabel(String key) => text('filter.$key');

  String kindLabel(String key) => text('kind.$key');

  /// Whether [languageCode] defines [key] itself, without English fallback.
  /// This is intentionally public so completeness tests can enforce parity.
  static bool hasOwnTranslation(String languageCode, String key) {
    return _values[languageCode.toLowerCase()]?.containsKey(key) ?? false;
  }

  static Set<String> ownTranslationKeys(String languageCode) {
    return Set<String>.unmodifiable(
      _values[languageCode.toLowerCase()]?.keys ?? const <String>[],
    );
  }

  /// User-facing JSON fields that require an entry in every locale whenever
  /// the corresponding base field is present and non-empty.
  static Set<String> get translatableContentFields =>
      Set<String>.unmodifiable(_displayFields);

  /// Returns a view of [source] with translated display fields overlaid.
  /// Technical fields such as `id`, `type`, coordinates and URLs are never
  /// replaced, even if malformed content attempts to translate them.
  Map<String, dynamic> contentFor(Map<String, dynamic> source) {
    if (languageCode == 'en') return source;
    final translations = source['translations'];
    if (translations is! Map) return source;
    final translated = translations[languageCode];
    if (translated is! Map) return source;

    final result = Map<String, dynamic>.from(source);
    for (final field in translated.entries) {
      final key = field.key.toString();
      if (_displayFields.contains(key) && field.value != null) {
        result[key] = field.value;
      }
    }
    return result;
  }

  /// Includes both the active-language content and canonical English content
  /// so newcomers can search using either script or official English names.
  String searchableText(Map<String, dynamic> source) {
    final localised = contentFor(source);
    final values = <Object?>[];
    for (final key in _searchableFields) {
      values
        ..add(localised[key])
        ..add(source[key]);
    }
    return values
        .where((value) => value != null)
        .map((value) => value is List ? value.join(' ') : value.toString())
        .join(' ');
  }

